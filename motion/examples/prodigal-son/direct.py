def span(s, i):
    a, _ = L(s, i)
    return (0.0 if (s, i) == (1, 0) else a), S(s, i)


def cut(s, i, parts):
    """split a line's span into shots; parts = [(weight, kind, kw)]; returns list of (t0, t1)"""
    a, b = span(s, i); tot = sum(p[0] for p in parts); t = a; out = []
    for k, (w, kind, kw) in enumerate(parts):
        t1 = b if k == len(parts) - 1 else round(t + (b - a) * w / tot, 3)
        sc = kw.pop("sc"); out.append((t, t1)); f.shot(sc, t, t1, kind, **kw) if kind != "insert3d" else f.insert3d(sc, t, t1, **kw); t = t1
    return out


